package com.mightyoung.muyon.androidlab
fun runChatReadChecks() {
    check(!ChatReadBounds.validText(" \n"))
    check(ChatReadBounds.validText("a".repeat(4096)))
    check(!ChatReadBounds.validText("a".repeat(4097)))
    check(!ChatReadBounds.validText("供".repeat(1366)))
    check(ChatReadBounds.validSelection("a".repeat(128)))
    check(!ChatReadBounds.validSelection("a".repeat(129)))
    check(ChatReadBounds.validReply("a".repeat(65536)))
    check(!ChatReadBounds.validReply("a".repeat(65537)))
    check(ChatReadConversation(status="unknown",requestId="original").requestId=="original")
    val original=ChatReadConversation(requestId="request",runId="run",admittedServiceEpoch="old-epoch",answer="hidden",receipt="original-ref",projection="hidden",status="completed",cursor=4,originalReceiptIdentity="original")
    val recovered=original.disclosureLost("binder_lost")
    check(recovered.cursor==0L && recovered.answer.isEmpty() && recovered.projection==null && recovered.receipt==null)
    check(recovered.requestId==original.requestId && recovered.runId==original.runId && recovered.admittedServiceEpoch==original.admittedServiceEpoch && recovered.originalReceiptIdentity==original.originalReceiptIdentity)
    val disclosureDenied=original.copy(status="unknown",reason="DISCLOSURE_UNAVAILABLE").finishEnvelope(true,0)
    check(disclosureDenied.status=="unknown" && disclosureDenied.reason=="DISCLOSURE_UNAVAILABLE")
    check(disclosureDenied.answer.isEmpty() && disclosureDenied.projection==null && disclosureDenied.receipt==null && disclosureDenied.originalReceiptIdentity=="original")
    check(runCatching{original.copy(status="unknown").finishEnvelope(true,1)}.isFailure)
    check(runCatching{original.copy(status="events").finishEnvelope(true,0)}.isFailure)
    val host=ChatReadConversation(requestId="host").withServiceSource(false)
    check(!host.synthetic)
    val boundHost=host.copy(runId="run",admittedServiceEpoch="epoch")
    check(!boundHost.withServiceSource(false).disclosureLost("lost").synthetic)
    check(runCatching{boundHost.withServiceSource(true)}.isFailure)
    check(runCatching{ChatReadConversation(runId="run").withServiceSource(false)}.isFailure)
    check(ChatReadConversation(runId="run").withServiceSource(true).synthetic)
    check(runCatching{host.copy(admittedServiceEpoch="epoch").withServiceSource(true)}.isFailure)
    println("PASS 21 chat read bounds, identity and immutable Service source checks; Binder/native NOT_RUN")
}
