import 'dart:convert';

import 'package:crypto/crypto.dart';
import 'package:flutter_test/flutter_test.dart';
import 'package:muyon/platform/grants/local_export_target.dart';
import 'package:muyon/platform/local_export_ledger.dart';
import 'package:muyon/platform/storage_manager.dart';
import 'package:muyon_module_api/muyon_module_api.dart';
import 'package:sqlite3/sqlite3.dart';

void main() {
  late ManagedConnection db;
  late LocalExportLedger ledger;
  late LocalExportTargetIssuer issuer;
  final now = DateTime.utc(2026, 10, 12);
  Matcher error(String code) => throwsA(
    isA<LocalExportLedgerException>().having((e) => e.code, 'code', code),
  );
  LocalExportPreparation preparation({
    String body = 'synthetic report',
    String? manifest,
  }) => LocalExportPreparation(
    kind: LocalExportKind.report,
    formatVersion: '1',
    mimeType: 'text/markdown',
    generatedAt: now,
    bytes: utf8.encode(body),
    sha256: sha256.convert(utf8.encode(body)).toString(),
    sources: const [
      ObjectRef(
        moduleId: 'research',
        objectType: 'entry',
        objectId: 'e1',
        revisionRef: 'r1',
      ),
    ],
    dedupedObjectCount: 1,
    exclusions: const [],
    warnings: const [],
    preparationVersion: 1,
    manifestDigest: manifest ?? 'a' * 64,
  );
  LocalExportLedgerRequest request({
    String export = 'export1',
    String invocation = 'generate1',
    LocalExportPhase phase = LocalExportPhase.generate,
    String? scope,
    LocalExportPreparation? prep,
    LocalExportTargetCapability? target,
    String? attempt,
    Map<String, Object?> metadata = const {},
  }) => LocalExportLedgerRequest(
    exportId: export,
    toolId: 'research.export_report',
    invocationId: invocation,
    phase: phase,
    scopeDigest: scope ?? 'b' * 64,
    preparation: prep ?? preparation(),
    targetIssuer: issuer,
    target: target,
    attemptId: attempt,
    policyVersion: 'p1',
    hostMetadata: metadata,
  );
  Future<LocalExportStageCompletion> success(List<int> _) async =>
      LocalExportStageCompletion(
        LocalExportStage(LocalExportOutcome.succeeded),
      );
  Future<void> generate() async {
    expect(
      (await ledger.execute(request(), operation: success)).state,
      LocalExportLedgerState.succeeded,
    );
  }

  setUp(() {
    db = ManagedConnection(sqlite3.openInMemory());
    LocalExportLedger.createTables(db.raw);
    ledger = LocalExportLedger(db, clock: () => now);
    issuer = LocalExportTargetIssuer();
  });
  tearDown(() => db.close());

  for (final mutation in ['bytes', 'scope', 'manifest']) {
    test(
      'fresh save invocation with changed $mutation refuses before callback',
      () async {
        await generate();
        var calls = 0;
        final req = request(
          invocation: 'fresh-save',
          phase: LocalExportPhase.save,
          attempt: 'fresh-attempt',
          target: issuer.issue('synthetic-target'),
          prep: mutation == 'bytes'
              ? preparation(body: 'changed')
              : mutation == 'manifest'
              ? preparation(manifest: 'c' * 64)
              : null,
          scope: mutation == 'scope' ? 'd' * 64 : null,
        );
        await expectLater(
          ledger.execute(
            req,
            operation: (bytes) async {
              calls++;
              return success(bytes);
            },
          ),
          error('export_identity_conflict'),
        );
        expect(calls, 0);
        expect(ledger.read('export1')!.saveAttempts, isEmpty);
      },
    );
  }
  test('fresh save with exact generated bytes and scope succeeds', () async {
    await generate();
    var calls = 0;
    final saved = await ledger.execute(
      request(
        invocation: 'fresh-save',
        phase: LocalExportPhase.save,
        attempt: 'fresh-attempt',
        target: issuer.issue('synthetic-target'),
      ),
      operation: (bytes) async {
        calls++;
        expect(bytes, preparation().bytes);
        return success(bytes);
      },
    );
    expect(saved.state, LocalExportLedgerState.succeeded);
    expect(calls, 1);
  });
  test(
    'revocation at pending commit durably cancels with exact safe code',
    () async {
      await generate();
      final target = issuer.issue('synthetic-target');
      final req = request(
        invocation: 'save-revoked',
        phase: LocalExportPhase.save,
        attempt: 'r1',
        target: target,
      );
      db.onCommit = () => issuer.revoke(target);
      var calls = 0;
      final saved = await ledger.execute(
        req,
        operation: (bytes) async {
          calls++;
          return success(bytes);
        },
      );
      expect(calls, 0);
      expect(saved.state, LocalExportLedgerState.cancelled);
      expect(saved.errorCode, 'export_target_expired');
      final row = db.raw
          .select(
            "SELECT state,error_code FROM local_export_attempts WHERE invocation_id='save-revoked'",
          )
          .single;
      expect(Map<String, Object?>.from(row), {
        'state': 'cancelled',
        'error_code': 'export_target_expired',
      });
      expect(ledger.read('export1')!.saveAttempts.single.modelData, {
        'status': 'cancelled',
        'errorCode': 'export_target_expired',
      });
    },
  );
  test(
    'unknown generation and receipt have exact safe projection fields',
    () async {
      final unknown = await ledger.execute(
        request(),
        operation: (_) async => throw StateError('SYNTHETIC_PRIVATE_ERROR'),
      );
      expect(unknown.state, LocalExportLedgerState.unknown);
      expect(unknown.errorCode, 'export_execution_unknown');
      final receipt = ledger.read('export1')!;
      expect(receipt.modelData, {
        'exportId': 'export1',
        'contentDigest': preparation().sha256,
        'manifestDigest': preparation().manifestDigest,
        'byteCount': preparation().byteCount,
        'generate': {
          'status': 'unknown',
          'errorCode': 'export_execution_unknown',
        },
        'saveAttempts': <Object?>[],
      });
    },
  );
  test(
    'readonly observed save success cannot unlock an unknown save identity',
    () async {
      await generate();
      await ledger.execute(
        request(
          invocation: 'unknown-save',
          phase: LocalExportPhase.save,
          attempt: 'u1',
          target: issuer.issue('one'),
        ),
        operation: (_) async => throw StateError('synthetic unknown'),
      );
      final before = db.raw
          .select('SELECT * FROM local_export_attempts')
          .map((r) => Map<String, Object?>.from(r))
          .toList();
      final checked = await ledger.check(
        'export1',
        probe: (_) async => LocalExportStageCompletion(
          LocalExportStage(LocalExportOutcome.succeeded),
        ),
      );
      expect(
        checked!.saveAttempts.single.state,
        LocalExportLedgerState.succeeded,
      );
      expect(checked.saveAttempts.single.modelData, {
        'status': 'unknown',
        'errorCode': 'export_execution_unknown',
      });
      var calls = 0;
      await expectLater(
        ledger.execute(
          request(
            invocation: 'new-save',
            phase: LocalExportPhase.save,
            attempt: 'u2',
            target: issuer.issue('two'),
          ),
          operation: (bytes) async {
            calls++;
            return success(bytes);
          },
        ),
        error('export_requires_check'),
      );
      expect(calls, 0);
      expect(
        db.raw
            .select('SELECT * FROM local_export_attempts')
            .map((r) => Map<String, Object?>.from(r))
            .toList(),
        before,
      );
    },
  );
  test(
    'read rejects corrupted persisted content SHA with exact safe failure',
    () async {
      await generate();
      db.raw.execute('UPDATE local_export_exports SET content=?', [
        utf8.encode('corrupted synthetic content'),
      ]);
      var commits = 0;
      db.onCommit = () => commits++;
      expect(() => ledger.read('export1'), error('ledger_read_failed'));
      expect(commits, 0);
    },
  );
  test(
    'zero-row completion update remains interrupted and cannot claim success',
    () async {
      db.raw.execute(
        "CREATE TRIGGER suppress_completion BEFORE UPDATE ON local_export_attempts BEGIN SELECT RAISE(IGNORE); END",
      );
      final result = await ledger.execute(request(), operation: success);
      expect(result.state, LocalExportLedgerState.interrupted);
      expect(result.errorCode, 'ledger_completion_failed');
      expect(
        db.raw
            .select('SELECT state FROM local_export_attempts')
            .single['state'],
        'pending',
      );
      expect(
        LocalExportLedger(db).read('export1')!.generate!.state,
        LocalExportLedgerState.unknown,
      );
    },
  );
  test('explicit fresh export identity can proceed while old unknown stays blocked', () async {
    await generate();
    await ledger.execute(
      request(
        invocation: 'old-uncertain-save',
        phase: LocalExportPhase.save,
        attempt: 'old-attempt',
        target: issuer.issue('old-target'),
      ),
      operation: (_) async => throw StateError('synthetic uncertain effect'),
    );
    final old = ledger.read('export1')!.modelData;
    var calls = 0;
    await ledger.execute(
      request(export: 'freshExport', invocation: 'fresh-generate'),
      operation: (bytes) async {
        calls++;
        return success(bytes);
      },
    );
    await ledger.execute(
      request(
        export: 'freshExport',
        invocation: 'fresh-save',
        phase: LocalExportPhase.save,
        attempt: 'fresh-attempt',
        target: issuer.issue('fresh-target'),
      ),
      operation: (bytes) async {
        calls++;
        return success(bytes);
      },
    );
    expect(calls, 2);
    expect(ledger.read('export1')!.modelData, old);
    expect(
      ledger.read('freshExport')!.saveAttempts.single.state,
      LocalExportLedgerState.succeeded,
    );
    // This exercises explicit identities only: fresh approval and duplication warning remain host responsibilities.
  });
}
